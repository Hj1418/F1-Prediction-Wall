export const APPROVED_SCENARIOS: StrategyScenario[] = STRATEGY_SCENARIO_BANK;

/**
 * Returns all approved strategy scenarios.
 */
export function getApprovedScenarios(): StrategyScenario[] {
  return STRATEGY_SCENARIO_BANK.filter(s => s.status === 'approved');
}

/**
 * Retrieves a specific scenario by ID.
 */
export function getScenarioById(scenarioId: string): StrategyScenario | undefined {
  return STRATEGY_SCENARIO_BANK.find(s => s.id === scenarioId);
}

/**
 * Filters scenarios by category, difficulty, or mode.
 */
export function filterScenarios(filters: {
  mode?: string;
  category?: string;
  difficulty?: string;
}): StrategyScenario[] {
  return getApprovedScenarios().filter(s => {
    if (filters.mode && filters.mode !== 'all' && s.mode !== filters.mode) return false;
    if (filters.category && filters.category !== 'all' && s.category !== filters.category) return false;
    if (filters.difficulty && filters.difficulty !== 'all' && s.difficulty !== filters.difficulty) return false;
    return true;
  });
}
