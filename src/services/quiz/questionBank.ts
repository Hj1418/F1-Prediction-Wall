/**
 * Validates the question bank according to Section 4 & 13 of the prompt:
 * - Exactly 4 distinct options per question
 * - Exactly one valid correct answer key
 * - Required explanation and verification metadata
 * - Approved status required for publication
 * - No duplicate question IDs
 */
export function validateQuestionBank(pool: QuizQuestion[] = VERIFIED_QUESTION_BANK): {
  isValid: boolean;
  totalCount: number;
  approvedCount: number;
  countByCategory: Record<string, number>;
  errors: string[];
} {
  const errors: string[] = [];
  const seenIds = new Set<string>();
  const seenQuestionTexts = new Set<string>();
  const countByCategory: Record<string, number> = {};

  for (const q of pool) {
    // 1. Unique questionId
    if (!q.questionId || seenIds.has(q.questionId)) {
      errors.push(`Duplicate or missing questionId: ${q.questionId}`);
    }
    seenIds.add(q.questionId);

    // 2. Duplicate question text check across the bank
    const normalizedText = (q.question || '').trim().toLowerCase();
    if (!normalizedText) {
      errors.push(`Question ${q.questionId} has empty question text`);
    } else if (seenQuestionTexts.has(normalizedText)) {
      errors.push(`Question ${q.questionId} has duplicate question text across question bank`);
    }
    seenQuestionTexts.add(normalizedText);

    // 3. Category tracking
    countByCategory[q.categoryId] = (countByCategory[q.categoryId] || 0) + 1;

    // 4. Exactly 4 distinct options with stable IDs
    if (!Array.isArray(q.options) || q.options.length !== 4) {
      errors.push(`Question ${q.questionId} must have exactly 4 options. Found: ${q.options?.length}`);
    } else {
      const optionIds = new Set(q.options.map(o => o.id));
      const optionTexts = new Set(q.options.map(o => o.text.trim().toLowerCase()));
      if (optionIds.size !== 4) {
        errors.push(`Question ${q.questionId} has non-unique option IDs`);
      }
      if (optionTexts.size !== 4) {
        errors.push(`Question ${q.questionId} has duplicate option texts`);
      }

      // Check each option text is non-empty
      for (const opt of q.options) {
        if (!opt.text || opt.text.trim().length === 0) {
          errors.push(`Question ${q.questionId} option '${opt.id}' has empty text`);
        }
      }

      // 5. Correct answer exists in options
      if (!optionIds.has(q.correctOptionId)) {
        errors.push(`Question ${q.questionId} correctOptionId '${q.correctOptionId}' is not in options`);
      }
    }

    // 6. Explanation required
    if (!q.explanation || q.explanation.trim().length < 15) {
      errors.push(`Question ${q.questionId} lacks adequate factual explanation`);
    }

    // 7. Source URL required and must be valid URL scheme
    if (!q.sourceUrl || (!q.sourceUrl.startsWith('http://') && !q.sourceUrl.startsWith('https://'))) {
      errors.push(`Question ${q.questionId} lacks valid HTTP/HTTPS verification source reference: ${q.sourceUrl}`);
    }

    // 8. Difficulty level validation
    if (!['easy', 'medium', 'hard'].includes(q.difficulty)) {
      errors.push(`Question ${q.questionId} has invalid difficulty: '${q.difficulty}'`);
    }

    // 9. Topic and Context metadata
    if (!q.topic || q.topic.trim().length === 0) {
      errors.push(`Question ${q.questionId} lacks topic metadata`);
    }
    if (!q.context || q.context.trim().length === 0) {
      errors.push(`Question ${q.questionId} lacks regulation / historical context metadata`);
    }

    // 10. Content version check
    if (typeof q.contentVersion !== 'number' || q.contentVersion < 1) {
      errors.push(`Question ${q.questionId} has invalid contentVersion: ${q.contentVersion}`);
    }

    // 11. Approval status check
    if (q.approvalStatus !== 'approved') {
      errors.push(`Question ${q.questionId} is not approved (status: ${q.approvalStatus})`);
    }
  }

  const approvedCount = pool.filter(q => q.approvalStatus === 'approved').length;

  return {
    isValid: errors.length === 0,
    totalCount: pool.length,
    approvedCount,
    countByCategory,
    errors,
  };
}

/**
 * Returns only approved questions for live publication pool
 */
export function getApprovedQuestions(): QuizQuestion[] {
  return VERIFIED_QUESTION_BANK.filter(q => q.approvalStatus === 'approved');
}

/**
 * Returns approved questions for a specific category
 */
export function getQuestionsForCategory(categoryId: string): QuizQuestion[] {
  return getApprovedQuestions().filter(q => q.categoryId === categoryId);
}
